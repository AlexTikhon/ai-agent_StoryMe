#!/usr/bin/env node
/**
 * Disposable production-container release smoke (`pnpm smoke:release`).
 *
 *   pnpm smoke:release                       build apps/api/Dockerfile, then run
 *   pnpm smoke:release -- --image <tag>      reuse an already-built API image
 *
 * One invocation owns one fresh Compose project `storyme-release-<16 hex>`:
 * PostgreSQL, Redis and a SeaweedFS S3 gateway on an internal network, plus the
 * API and a separate worker started from the same image with NODE_ENV=production
 * and their compiled entrypoints. Only the API port is published, on loopback.
 * Every credential is generated per invocation; nothing is read from .env files
 * and the Docker CLI receives an allowlisted environment.
 *
 * Exit status: 0 pass, 1 failure, 2 usage, 3 Docker unavailable,
 * 128+n interrupted. Cleanup of this project's containers, networks and
 * volumes runs on success, failure and interruption. The generated Compose
 * directory is deleted only after teardown is verified; otherwise it is kept
 * and the summary prints a recovery command that names it with -f.
 * See docs/release-smoke.md.
 */
