/** Only a project name generated by this script may ever be started or removed. */
export function assertOwnedProject(project) {
  if (typeof project !== 'string' || !PROJECT_PATTERN.test(project)) {
    throw new Error(`Refusing to operate on a Compose project this smoke does not own: ${project}`);
  }
  return project;
}

/** Fresh identifiers and disposable credentials for one invocation (hex only: no quoting or interpolation hazards). */
export function createInvocation(random = randomBytes) {
  const id = random(8).toString('hex');
  const secret = () => random(24).toString('hex');
  const account = (role, name) => ({
    name,
    email: `${role}-${id}@release-smoke.storyme.test`,
    password: `Smoke1${secret().slice(0, 20)}`,
  });
  return Object.freeze({
    id,
    project: assertOwnedProject(`storyme-release-${id}`),
    database: { name: `storyme_release_${id}`, role: `storyme_release_${id}`, password: secret() },
    storage: {
      bucket: `storyme-release-${id}`,
      region: 'us-east-1',
      accessKeyId: `release${id}`,
      secretAccessKey: secret(),
    },
    jwt: { access: secret(), refresh: secret() },
    accounts: {
      owner: account('owner', 'Release Smoke Owner'),
      other: account('other', 'Release Smoke Other'),
    },
  });
}

