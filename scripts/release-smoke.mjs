export function parseArguments(argv) {
  const args = argv[0] === '--' ? argv.slice(1) : [...argv];
  let image;
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    let value;
    if (arg === '--image') value = args[++index];
    else if (arg.startsWith('--image=')) value = arg.slice('--image='.length);
    else throw new Error(`Unknown argument: ${arg}`);
    if (image !== undefined) throw new Error('--image may be given only once.');
    if (!value || !IMAGE_PATTERN.test(value)) throw new Error('--image requires an image tag.');
    image = value;
  }
  return { image };
}

function lines(text) {
  return String(text)
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
}

function tail(text, max = 4000) {
  const value = String(text ?? '').trim();
  return value.length > max ? `…${value.slice(-max)}` : value;
}

function describeResult(result) {
  if (result.timedOut) return `timed out after ${Math.round(result.timeoutMs / 1000)}s`;
  if (result.error) return result.error.message;
  return result.status === null ? `signal ${result.signal}` : `exit ${result.status}`;
}

class StepFailure extends Error {
  constructor(message, status = EXIT.fail) {
    super(message);
    this.status = status;
  }
}

/**
 * The smoke lifecycle with process, HTTP and filesystem operations injectable.
 * `run` never throws and resolves to the exit status; `cancel` stops the
 * running child and lets cleanup of this invocation's resources proceed.
 */
export function createReleaseSmoke(options = {}) {
  const invocation = options.invocation ?? createInvocation();
  const project = assertOwnedProject(invocation.project);
  const execute = options.execute ?? runCommand;
  const journey = options.journey ?? runReleaseJourney;
  const probeHealth = options.probeHealth ?? defaultProbeHealth;
  const writeSpec = options.writeSpec ?? defaultWriteSpec;
  const removeSpec = options.removeSpec ?? ((directory) => rmSync(directory, { recursive: true }));
  const log = options.log ?? ((message) => console.log(message));
  const logError = options.logError ?? ((message) => console.error(message));
  const sleep = options.sleep ?? ((ms) => new Promise((done) => setTimeout(done, ms)));
  const now = options.now ?? (() => performance.now());
  const platform = options.platform ?? process.platform;
  const env = dockerEnvironment(options.env ?? process.env);
  const timeouts = {
    buildMs: 1_800_000,
    infraMs: 240_000,
    readyMs: 120_000,
    generationMs: 180_000,
    ...options.timeouts,
  };

  // teardownVerified: `compose down` succeeded AND enumeration found nothing
  // labelled with this project. Only then may the spec directory be deleted.
  const owned = {
    compose: false,
    specDirectory: null,
    teardownVerified: false,
    specRemoved: false,
  };
  const running = new Set();
  let cancelled = null;
  let image = DEFAULT_IMAGE;
  let imageProvided = false;
  let specPath = null;
  let apiBaseUrl = null;

  function cancel(signal = 'SIGINT') {
    if (cancelled) {
      log('[smoke:release] Cleanup already in progress; waiting for it to finish.');
      return;
    }
    cancelled = signal;
    log(`\n[smoke:release] ${signal} received; stopping and removing ${project}...`);
    for (const stop of running) void stop();
  }

  const checkCancelled = () => {
    if (cancelled) throw new StepFailure(`interrupted by ${cancelled}`);
  };

  async function run(command, args, runOptions = {}) {
    if (!runOptions.cleanup) checkCancelled();
    const result = await execute(command, args, {
      cwd: repoRoot,
      env,
      timeoutMs: 120_000,
      ...runOptions,
      track: (stop) => {
        if (runOptions.cleanup) return () => {};
        running.add(stop);
        return () => running.delete(stop);
      },
    });
    if (!runOptions.cleanup) checkCancelled();
    return result;
  }

  async function docker(args, runOptions = {}) {
    const result = await run('docker', args, runOptions);
    if (runOptions.allowFailure || (result.status === 0 && !result.timedOut && !result.error)) {
      return result;
    }
    const detail = tail(result.stderr || result.stdout, 1500);
    const label = runOptions.label ?? `docker ${args.slice(0, 2).join(' ')}`;
    throw new StepFailure(`${label}: ${describeResult(result)}${detail ? `\n${detail}` : ''}`);
  }

  const compose = (args, runOptions = {}) =>
    docker(['compose', '-p', project, '-f', specPath, ...args], {
      cwd: owned.specDirectory,
      label: `docker compose ${args.slice(0, 2).join(' ')}`,
      ...runOptions,
    });

  const tools = (args, runOptions = {}) =>
    compose(['run', '--rm', '--no-deps', '-T', 'tools', ...args], runOptions);

  const psql = async (sql) => {
    const { database } = invocation;
    const result = await compose([
      'exec',
      '-T',
      'postgres',
      'psql',
      '-X',
      '-q',
      '-A',
      '-t',
      '-v',
      'ON_ERROR_STOP=1',
      '-U',
      database.role,
      '-d',
      database.name,
      '-c',
      sql,
    ]);
    return lines(result.stdout);
  };

  async function containerId(service) {
    const id = lines((await compose(['ps', '-q', service])).stdout)[0];
    if (!id) throw new StepFailure(`${service} container is not running`);
    return id;
  }

  async function serviceState(service) {
    const result = await compose(['ps', '-a', '--format', 'json', service]);
    const entry = lines(result.stdout)
      .map((line) => JSON.parse(line))
      .flat()[0];
    return entry ? { state: entry.State, exitCode: entry.ExitCode } : { state: 'missing' };
  }

  async function assertRunning(service) {
    const { state, exitCode } = await serviceState(service);
    if (state !== 'running') {
      throw new StepFailure(`${service} container is ${state} (exit ${exitCode ?? '?'})`);
    }
  }

  /** Runtime posture of an application container, inspected rather than assumed. */
  async function checkPosture(service, entrypoint) {
    const inspected = JSON.parse(
      (await docker(['inspect', '--format', '{{json .}}', await containerId(service)])).stdout,
    );
    const runtime = JSON.parse(
      (
        await compose([
          'exec',
          '-T',
          service,
          'node',
          '-e',
          "process.stdout.write(JSON.stringify({uid:process.getuid(),cmd:require('fs').readFileSync('/proc/1/cmdline','utf8').split('\\0').filter(Boolean),nodeEnv:process.env.NODE_ENV,worker:process.env.ENABLE_GENERATION_WORKER??null}))",
        ])
      ).stdout,
    );
    const problems = [];
    if (runtime.uid === 0) problems.push('runs as root');
    if (runtime.cmd.join(' ') !== `node ${entrypoint}`) {
      problems.push(`PID 1 is "${runtime.cmd.join(' ')}", expected "node ${entrypoint}"`);
    }
    if (runtime.nodeEnv !== 'production') problems.push(`NODE_ENV=${runtime.nodeEnv}`);
    if ((inspected.Mounts ?? []).length > 0) {
      problems.push(`has mounts: ${inspected.Mounts.map((mount) => mount.Destination).join(', ')}`);
    }
    const health = inspected.Config?.Healthcheck?.Test ?? [];
    const bindings = Object.entries(inspected.HostConfig?.PortBindings ?? {});
    if (service === 'api') {
      if (runtime.worker !== 'false') problems.push('ENABLE_GENERATION_WORKER is not "false"');
      if (!health.join(' ').includes('/api/health')) problems.push("lost the image's healthcheck");
      const hosts = bindings.flatMap(([, list]) => (list ?? []).map((entry) => entry.HostIp));
      if (bindings.length !== 1 || hosts.some((host) => host !== '127.0.0.1')) {
        problems.push(`publishes ${JSON.stringify(inspected.HostConfig?.PortBindings)}`);
      }
    } else {
      if (health[0] !== 'NONE') problems.push(`healthcheck is ${JSON.stringify(health)}`);
      if (bindings.length > 0) problems.push('publishes ports');
    }
    if (problems.length > 0) throw new StepFailure(`${service} posture: ${problems.join('; ')}`);
    log(
      `[smoke:release] ${service}: uid ${runtime.uid}, PID 1 "node ${entrypoint}", ` +
        `NODE_ENV=production, no mounts${service === 'api' ? ', loopback-only port' : ', no healthcheck, no ports'}`,
    );
  }

  async function waitForApi() {
    const port = lines((await compose(['port', 'api', String(CONTAINER_PORT)])).stdout)[0] ?? '';
    const match = /^127\.0\.0\.1:(\d+)$/.exec(port);
    if (!match) throw new StepFailure(`API port is not bound to loopback: "${port}"`);
    const baseUrl = `http://127.0.0.1:${match[1]}/api`;
    const deadline = Date.now() + timeouts.readyMs;
    for (;;) {
      checkCancelled();
      if (await probeHealth(`${baseUrl}/health`)) return baseUrl;
      await assertRunning('api');
      if (Date.now() >= deadline) {
        throw new StepFailure(`API not healthy within ${timeouts.readyMs / 1000}s at ${baseUrl}`);
      }
      await sleep(1_000);
    }
  }

  async function waitForWorker(minimumReadyLines) {
    const deadline = Date.now() + timeouts.readyMs;
    for (;;) {
      const output = (await compose(['logs', '--no-color', 'worker'])).stdout;
      if (output.split(WORKER_READY).length - 1 >= minimumReadyLines) return;
      await assertRunning('worker');
      if (Date.now() >= deadline) {
        throw new StepFailure(`worker did not log "${WORKER_READY}" within ${timeouts.readyMs}ms`);
      }
      await sleep(1_000);
    }
  }

  const s3Script = (body) =>
    `const s3=require('@aws-sdk/client-s3');const c=new s3.S3Client({region:process.env.PDF_STORAGE_REGION,endpoint:process.env.PDF_STORAGE_ENDPOINT,forcePathStyle:true,credentials:{accessKeyId:process.env.PDF_STORAGE_ACCESS_KEY_ID,secretAccessKey:process.env.PDF_STORAGE_SECRET_ACCESS_KEY}});const B=process.env.PDF_STORAGE_BUCKET;(async()=>{${body}})().catch(e=>{console.error(e.name+': '+e.message);process.exit(1)});`;

  const infra = {
    apiBaseUrl: async () => apiBaseUrl,
    async markAccountsVerified(emails) {
      if (!emails.every((email) => EMAIL_PATTERN.test(email))) {
        throw new StepFailure('refusing to verify an account outside the synthetic smoke domain');
      }
      const list = emails.map((email) => `'${email}'`).join(', ');
      const rows = await psql(
        'UPDATE users SET email_verified = true, email_verified_at = now(), ' +
          'email_verification_token_hash = NULL, email_verification_expires_at = NULL ' +
          `WHERE email IN (${list}) AND email_verified = false RETURNING email`,
      );
      return rows.filter((row) => emails.includes(row));
    },
    async generationOutbox() {
      const rows = await psql(
        'SELECT aggregate_type, aggregate_id, status FROM outbox_events ORDER BY created_at',
      );
      return rows.map((row) => {
        const [aggregateType, aggregateId, status] = row.split('|');
        return { aggregateType, aggregateId, status };
      });
    },
    async waitingGenerationJobs() {
      const result = await compose([
        'exec',
        '-T',
        'redis',
        'redis-cli',
        'LRANGE',
        'bull:book-generation:wait',
        '0',
        '-1',
      ]);
      return lines(result.stdout);
    },
    async startWorker() {
      await compose(['up', '-d', '--no-deps', 'worker'], { timeoutMs: timeouts.readyMs });
      await waitForWorker(1);
      await checkPosture('worker', 'dist/worker');
    },
    async restartApplication() {
      await compose(['restart', '--timeout', '20', 'api', 'worker'], {
        timeoutMs: timeouts.readyMs,
      });
      apiBaseUrl = await waitForApi();
      await waitForWorker(2);
      log('[smoke:release] API and worker restarted; infrastructure untouched');
      return apiBaseUrl;
    },
  };

  const steps = [
    {
      label: 'Docker prerequisites',
      unavailable: true,
      async action() {
        for (const args of [
          ['version', '--format', '{{.Server.Version}}'],
          ['compose', 'version', '--short'],
        ]) {
          const result = await run('docker', args, { timeoutMs: 30_000 });
          if (result.status !== 0 || result.timedOut || result.error) {
            throw new StepFailure(
              `docker ${args[0] === 'compose' ? 'compose ' : ''}is not available (${describeResult(result)}). ` +
                'Start Docker and retry; nothing was started.',
              EXIT.unavailable,
            );
          }
        }
      },
    },
    {
      label: 'Build API image',
      skip: () => (imageProvided ? `reusing ${image}` : null),
      action: () =>
        docker(['build', '-f', 'apps/api/Dockerfile', '-t', image, '.'], {
          timeoutMs: timeouts.buildMs,
          stream: true,
        }),
    },
    {
      label: 'Native-dependency image smoke',
      async action() {
        const result = await run(process.execPath, ['scripts/api-image-smoke.mjs', image], {
          timeoutMs: 180_000,
          stream: true,
        });
        if (result.status !== 0) throw new StepFailure(`image smoke ${describeResult(result)}`);
      },
    },
    {
      label: 'Disposable PostgreSQL, Redis and S3',
      async action() {
        const existing = await listProjectResources();
        if (existing.length > 0) {
          throw new StepFailure(`${project} already has resources (${existing.join(', ')})`);
        }
        owned.specDirectory = writeSpec(project, buildComposeSpec(invocation, image));
        specPath = (platform === 'win32' ? win32 : posix).join(owned.specDirectory, 'compose.json');
        owned.compose = true;
        await compose(['up', '-d', '--wait', '--wait-timeout', '180', 'postgres', 'redis', 's3'], {
          timeoutMs: timeouts.infraMs,
          stream: true,
        });
      },
    },
    {
      label: 'Database identity',
      async action() {
        const result = await tools([
          '-e',
          "const{PrismaClient}=require('@prisma/client');const p=new PrismaClient();p.$queryRawUnsafe(\"select current_database() as database, current_user as role, (select count(*) from information_schema.tables where table_schema='public')::int as tables\").then(r=>{process.stdout.write(JSON.stringify(r[0]));return p.$disconnect()}).catch(e=>{console.error(e.message);process.exit(1)})",
        ]);
        const identity = JSON.parse(lines(result.stdout).at(-1));
        const { database } = invocation;
        if (identity.database !== database.name || identity.role !== database.role) {
          throw new StepFailure(
            `DATABASE_URL reached ${identity.database} as ${identity.role}, expected ` +
              `${database.name} as ${database.role}; refusing to migrate`,
          );
        }
        if (identity.tables !== 0) {
          throw new StepFailure(`database ${identity.database} is not empty; refusing to migrate`);
        }
        log(`[smoke:release] DATABASE_URL reaches empty ${identity.database} as ${identity.role}`);
      },
    },
    {
      label: 'Migrations (release image)',
      async action() {
        const result = await tools(['node_modules/prisma/build/index.js', 'migrate', 'deploy'], {
          timeoutMs: 180_000,
        });
        const output = lines(result.stdout);
        const applied = output.find((line) => /successfully applied/i.test(line));
        if (!applied) {
          throw new StepFailure(
            `prisma migrate deploy did not confirm: ${tail(output.join('\n'), 800)}`,
          );
        }
        log(
          `[smoke:release] ${output.find((line) => /migrations found/i.test(line)) ?? ''} ${applied}`,
        );
      },
    },
    {
      label: 'S3 bucket',
      action: () =>
        tools([
          '-e',
          s3Script(
            'await c.send(new s3.CreateBucketCommand({Bucket:B}));await c.send(new s3.HeadBucketCommand({Bucket:B}));',
          ),
        ]),
    },
    {
      label: 'API container (worker disabled)',
      async action() {
        await compose(['up', '-d', '--no-deps', 'api'], { timeoutMs: timeouts.readyMs });
        apiBaseUrl = await waitForApi();
        await checkPosture('api', 'dist/main');
      },
    },
    {
      label: 'Book journey',
      async action(state) {
        state.summary = await journey({
          infra,
          accounts: invocation.accounts,
          log,
          timeouts: { generationMs: timeouts.generationMs },
          shouldStop: () => Boolean(cancelled),
        });
      },
    },
    {
      label: 'Artifacts stored in S3',
      async action(state) {
        const result = await tools([
          '-e',
          s3Script(
            'let t;const k=[];do{const r=await c.send(new s3.ListObjectsV2Command({Bucket:B,ContinuationToken:t}));for(const o of r.Contents??[])k.push(o.Key);t=r.NextContinuationToken}while(t);process.stdout.write(JSON.stringify(k))',
          ),
        ]);
        const keys = JSON.parse(lines(result.stdout).at(-1));
        const forBook = keys.filter((key) => key.includes(state.summary.bookId));
        const minimum = Object.keys(state.summary.artifacts).length;
        if (forBook.length < minimum) {
          throw new StepFailure(
            `bucket holds ${forBook.length} object(s) for the book, expected ≥ ${minimum}`,
          );
        }
        log(
          `[smoke:release] bucket ${invocation.storage.bucket}: ${forBook.length} objects for the book`,
        );
      },
    },
  ];

  async function listProjectResources() {
    const label = `label=com.docker.compose.project=${project}`;
    const found = [];
    for (const [kind, args] of [
      ['container', ['ps', '-a', '-q', '--filter', label]],
      ['network', ['network', 'ls', '-q', '--filter', label]],
      ['volume', ['volume', 'ls', '-q', '--filter', label]],
    ]) {
      const result = await docker(args, { cleanup: true, timeoutMs: 30_000 });
      found.push(...lines(result.stdout).map((id) => `${kind} ${id.slice(0, 12)}`));
    }
    return found;
  }

  async function diagnostics() {
    if (!specPath) return;
    logError(`\n[smoke:release] ---- diagnostics for ${project} (bounded) ----`);
    for (const args of [
      ['ps', '-a'],
      ['logs', '--no-color', '--timestamps', '--tail', '80', 'api', 'worker', 's3'],
    ]) {
      const result = await compose(args, { cleanup: true, allowFailure: true, timeoutMs: 30_000 });
      logError(tail(`${result.stdout}\n${result.stderr}`, 12_000));
    }
    logError('[smoke:release] ---- end diagnostics ----\n');
  }

  async function cleanup() {
    const problems = [];
    if (owned.compose) {
      const down = await compose(['down', '--volumes', '--remove-orphans', '--timeout', '10'], {
        cleanup: true,
        allowFailure: true,
        timeoutMs: 180_000,
      });
      if (down.status !== 0 || down.timedOut || down.error) {
        problems.push(`compose down ${describeResult(down)}: ${tail(down.stderr, 500)}`);
      }
      try {
        const leftover = await listProjectResources();
        if (leftover.length > 0) problems.push(`still present: ${leftover.join(', ')}`);
      } catch (error) {
        problems.push(`could not list leftovers: ${error.message}`);
      }
      owned.teardownVerified = problems.length === 0;
    }
    // The generated Compose file is the only exact recovery handle: keep it
    // unless teardown was verified. Deleting it is deliberately the last step,
    // so a crash or hard kill anywhere before this point also leaves it.
    if (owned.specDirectory && owned.teardownVerified) {
      try {
        removeSpec(owned.specDirectory);
        owned.specRemoved = true;
      } catch (error) {
        problems.push(`could not remove ${owned.specDirectory}: ${error.message}`);
      }
    }
    return problems;
  }

  async function runSmoke(argv = []) {
    try {
      const parsed = parseArguments(argv);
      if (parsed.image) {
        image = parsed.image;
        imageProvided = true;
      }
    } catch (error) {
      logError(error.message);
      logError(USAGE);
      return EXIT.usage;
    }

    log(`[smoke:release] Compose project: ${project}; image: ${image}`);
    const results = [];
    const state = {};
    let failure = null;
    for (const step of steps) {
      if (failure || cancelled) {
        results.push({ step, status: 'NOT RUN' });
        continue;
      }
      const skipped = step.skip?.();
      if (skipped) {
        results.push({ step, status: 'SKIPPED', reason: skipped });
        continue;
      }
      log(`\n[smoke:release] ${step.label}`);
      const started = now();
      try {
        await step.action(state);
        results.push({ step, status: 'PASS', durationMs: now() - started });
      } catch (error) {
        const interrupted = Boolean(cancelled);
        const status =
          error instanceof StepFailure && error.status === EXIT.unavailable
            ? 'UNAVAILABLE'
            : 'FAIL';
        const reason = interrupted ? `interrupted by ${cancelled}` : error.message;
        results.push({ step, status, reason, durationMs: now() - started });
        failure = { exitCode: error instanceof StepFailure ? error.status : EXIT.fail };
      }
    }

    if (failure && !cancelled) {
      try {
        await diagnostics();
      } catch (error) {
        logError(`[smoke:release] diagnostics failed: ${error.message}`);
      }
    }
    let cleanupProblems;
    try {
      cleanupProblems = await cleanup();
    } catch (error) {
      cleanupProblems = [`cleanup crashed: ${error.message}`];
    }

    let exitCode = 0;
    if (cancelled) exitCode = 128 + (constants.signals[cancelled] ?? 2);
    else if (failure) exitCode = failure.exitCode;
    else if (cleanupProblems.length > 0) exitCode = EXIT.fail;
    log(
      formatSummary({
        project,
        results,
        exitCode,
        cancelled,
        cleanupProblems,
        owned,
        composeFile: specPath,
        platform,
      }),
    );
    return exitCode;
  }

  return { run: runSmoke, cancel, project, invocation };
}

/**
 * Quote one argument for the shell a user is likely to paste into: PowerShell
 * or cmd on Windows (paths there cannot contain `"`), a POSIX shell elsewhere.
 */
export function quoteShellArgument(value, platform = process.platform) {
  const text = String(value);
  if (platform === 'win32') return `"${text}"`;
  return `'${text.replace(/'/g, `'\\''`)}'`;
}

/** Copyable teardown that cannot pick up another Compose file from the working directory. */
export function recoveryCommand(project, composeFile, platform = process.platform) {
  return (
    `docker compose -p ${assertOwnedProject(project)} -f ` +
    `${quoteShellArgument(composeFile, platform)} down --volumes --remove-orphans`
  );
}

function cleanupLines({ project, cleanupProblems, owned, composeFile, platform }) {
  const removedResources = `Cleanup: removed every container, network and volume labelled ${project}`;
  if (owned.teardownVerified) {
    if (owned.specRemoved) return [`${removedResources}, and the generated Compose directory.`];
    return [
      `${removedResources}.`,
      `Cleanup INCOMPLETE: ${cleanupProblems.join('; ')}`,
      `  The directory holds only this run's disposable credentials; delete it manually.`,
    ];
  }
  const directory = owned.specDirectory;
  const label = `label=com.docker.compose.project=${project}`;
  return [
    `Cleanup INCOMPLETE: ${cleanupProblems.join('; ')}`,
    `  Kept the generated Compose configuration for recovery:`,
    `    ${composeFile}`,
    `  Recover with:`,
    `    ${recoveryCommand(project, composeFile, platform)}`,
    `  Then verify that each of these prints nothing:`,
    `    docker ps -a -q --filter ${label}`,
    `    docker network ls -q --filter ${label}`,
    `    docker volume ls -q --filter ${label}`,
    `  Only after that teardown succeeds and nothing remains, delete the kept directory:`,
    `    ${quoteShellArgument(directory, platform)}`,
  ];
}

export function formatSummary({
  project,
  results,
  exitCode,
  cancelled,
  cleanupProblems,
  owned,
  composeFile,
  platform = process.platform,
}) {
  const out = ['', '================== smoke:release summary ==================', ''];
  out.push(`Compose project: ${project}`, '');
  for (const result of results) {
    const duration =
      result.durationMs === undefined ? '-' : `${(result.durationMs / 1000).toFixed(1)}s`;
    out.push(`  ${result.status.padEnd(11)} ${duration.padStart(8)}  ${result.step.label}`);
    if (result.reason) out.push(`${' '.repeat(23)}${result.reason.split('\n')[0]}`);
  }
  if (owned.compose) {
    out.push('', ...cleanupLines({ project, cleanupProblems, owned, composeFile, platform }));
  } else {
    out.push('', 'Cleanup: nothing was started.');
  }
  let verdict = exitCode === 0 ? 'PASS' : `FAIL (exit ${exitCode})`;
  if (exitCode === EXIT.unavailable) verdict = `UNAVAILABLE (exit ${exitCode})`;
  if (cancelled) verdict = `CANCELLED by ${cancelled} (exit ${exitCode})`;
  out.push('', `Result: ${verdict}`, '', 'Not verified by this smoke:');
  for (const item of NOT_VERIFIED) out.push(`  - ${item}`);
  out.push('===========================================================');
  return out.join('\n');
}

