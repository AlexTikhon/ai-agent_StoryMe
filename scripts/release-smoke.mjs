/** Compose spec (JSON is valid YAML) written to a private temp directory, never into the repo. */
export function buildComposeSpec(invocation, image) {
  assertOwnedProject(invocation.project);
  const { database, storage } = invocation;
  const app = applicationEnvironment(invocation);
  const healthy = { condition: 'service_healthy' };
  const infrastructure = { postgres: healthy, redis: healthy, s3: healthy };
  const probe = (test) => ({ test, interval: '2s', timeout: '3s', retries: 60 });
  const identities = {
    identities: [
      {
        name: 'release-smoke',
        credentials: [{ accessKey: storage.accessKeyId, secretKey: storage.secretAccessKey }],
        actions: ['Admin', 'Read', 'Write', 'List', 'Tagging'],
      },
    ],
  };
  return {
    name: invocation.project,
    services: {
      postgres: {
        image: INFRA_IMAGES.postgres,
        environment: {
          POSTGRES_USER: database.role,
          POSTGRES_PASSWORD: database.password,
          POSTGRES_DB: database.name,
        },
        tmpfs: ['/var/lib/postgresql/data'],
        healthcheck: probe(['CMD-SHELL', `pg_isready -U ${database.role} -d ${database.name}`]),
      },
      redis: {
        image: INFRA_IMAGES.redis,
        command: ['redis-server', '--save', '', '--appendonly', 'no'],
        tmpfs: ['/data'],
        healthcheck: probe(['CMD', 'redis-cli', 'ping']),
      },
      s3: {
        image: INFRA_IMAGES.s3,
        command: [
          'server',
          '-dir=/data',
          '-ip=127.0.0.1',
          '-ip.bind=0.0.0.0',
          '-master.volumeSizeLimitMB=64',
          '-volume.max=8',
          '-s3',
          `-s3.port=${S3_PORT}`,
          '-s3.config=/etc/seaweedfs/s3.json',
        ],
        tmpfs: ['/data'],
        configs: [{ source: 's3_identities', target: '/etc/seaweedfs/s3.json' }],
        healthcheck: probe([
          'CMD',
          'wget',
          '-q',
          '-O',
          '/dev/null',
          `http://127.0.0.1:${S3_PORT}/healthz`,
        ]),
      },
      // One-off setup commands (identity check, migrations, bucket) run from
      // the release image itself; never started by `up`.
      tools: {
        image,
        profiles: ['tools'],
        entrypoint: ['node'],
        environment: { ...app, CHECKPOINT_DISABLE: '1' },
        healthcheck: { disable: true },
      },
      api: {
        image,
        command: ['node', 'dist/main'],
        environment: { ...app, ENABLE_GENERATION_WORKER: 'false' },
        ports: [`127.0.0.1::${CONTAINER_PORT}`],
        depends_on: infrastructure,
      },
      // No HTTP server: the image's /api/health probe would always fail here.
      worker: {
        image,
        command: ['node', 'dist/worker'],
        environment: app,
        healthcheck: { disable: true },
        depends_on: infrastructure,
      },
    },
    configs: { s3_identities: { content: JSON.stringify(identities) } },
  };
}

