function defaultWriteSpec(project, spec) {
  const directory = resolve(mkdtempSync(join(tmpdir(), `${assertOwnedProject(project)}-`)));
  writeFileSync(join(directory, 'compose.json'), JSON.stringify(spec, null, 2), { mode: 0o600 });
  return directory;
}

async function defaultProbeHealth(url) {
  try {
    const response = await fetch(url, { signal: AbortSignal.timeout(5_000) });
    return response.status === 200;
  } catch {
    return false;
  }
}

/**
 * Bounded child process without a shell. Captured output is capped; `stream`
 * forwards output for long builds. A timeout or cancellation stops the whole
 * process tree with the launcher's Windows-safe helper.
 */
export function runCommand(command, args, options) {
  const maxOutput = options.maxOutput ?? 2_000_000;
  return new Promise((done) => {
    let child;
    try {
      child = spawn(command, args, {
        cwd: options.cwd,
        env: options.env,
        shell: false,
        windowsHide: true,
        detached: process.platform !== 'win32',
        stdio: ['ignore', options.stream ? 'inherit' : 'pipe', options.stream ? 'inherit' : 'pipe'],
      });
    } catch (error) {
      done({ status: null, signal: null, stdout: '', stderr: '', error });
      return;
    }
    let stdout = '';
    let stderr = '';
    const append = (current, chunk) =>
      current.length >= maxOutput ? current : current + chunk.toString('utf8');
    child.stdout?.on('data', (chunk) => (stdout = append(stdout, chunk)));
    child.stderr?.on('data', (chunk) => (stderr = append(stderr, chunk)));
    let timedOut = false;
    const stop = () => defaultStopProcessTree(child).catch(() => {});
    const untrack = options.track?.(stop) ?? (() => {});
    const timer = setTimeout(() => {
      timedOut = true;
      void stop();
    }, options.timeoutMs);
    child.once('error', (error) => {
      clearTimeout(timer);
      untrack();
      done({ status: null, signal: null, stdout, stderr, error });
    });
    child.once('close', (status, signal) => {
      clearTimeout(timer);
      untrack();
      done({ status, signal, stdout, stderr, timedOut, timeoutMs: options.timeoutMs });
    });
  });
}

