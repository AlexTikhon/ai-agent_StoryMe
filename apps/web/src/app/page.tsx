function getApiHealthStatus(): { url: string | null; error: string | null } {
  try {
    return { url: `${getApiBase()}/health`, error: null };
  } catch (err) {
    return { url: null, error: err instanceof Error ? err.message : 'API URL is not configured.' };
  }
}

