import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { render, screen, within } from '@testing-library/react';
import SampleBookPage from './page';
import { SAMPLE_BOOK } from '@/sample-book/sample-book';

const PUBLIC_DIR = resolve(__dirname, '../../../public');

const SECTION_IDS = ['cover', 'page-1', 'page-2', 'page-3', 'page-4', 'back-cover'];

describe('SampleBookPage', () => {
  afterEach(() => {
    vi.restoreAllMocks();
  });

  it('renders the whole curated story from the canonical fixture', () => {
    render(<SampleBookPage />);

    expect(screen.getByRole('heading', { level: 1, name: SAMPLE_BOOK.title })).toBeDefined();
    for (const page of SAMPLE_BOOK.pages) {
      expect(
        screen.getByRole('heading', {
          level: 2,
          name: `Page ${page.pageNumber}: ${page.heading}`,
        }),
      ).toBeDefined();
      expect(screen.getByText(page.text)).toBeDefined();
    }
    expect(screen.getByRole('heading', { level: 2, name: 'Cover' })).toBeDefined();
    expect(screen.getByRole('heading', { level: 2, name: 'Back cover' })).toBeDefined();
    expect(screen.getByText(SAMPLE_BOOK.backCover.text)).toBeDefined();
  });

  it('identifies the content as a curated fictional sample, not AI output', () => {
    render(<SampleBookPage />);
    const note = screen.getByRole('complementary', { name: 'About this sample' });
    expect(note.textContent).toContain(SAMPLE_BOOK.provenance);
    expect(note.textContent).toMatch(/not generated by StoryMe's AI/);
  });

  it('gives every illustration its meaningful alternative and a bundled source', () => {
    render(<SampleBookPage />);
    const illustrations = [
      SAMPLE_BOOK.cover.illustration,
      ...SAMPLE_BOOK.pages.map((page) => page.illustration),
      SAMPLE_BOOK.backCover.illustration,
    ];
    expect(screen.getAllByRole('img')).toHaveLength(illustrations.length);
    for (const illustration of illustrations) {
      const img = screen.getByRole('img', { name: illustration.alt });
      expect(img.getAttribute('src')).toBe(illustration.src);
      expect(existsSync(resolve(PUBLIC_DIR, `.${illustration.src}`))).toBe(true);
    }
  });

  it('links contents and previous/next anchors to the sections in reading order', () => {
    const { container } = render(<SampleBookPage />);
    const contents = screen.getByRole('navigation', { name: 'Sample book pages' });
    const hrefs = within(contents)
      .getAllByRole('link')
      .map((link) => link.getAttribute('href'));
    expect(hrefs).toEqual(SECTION_IDS.map((id) => `#${id}`));
    for (const id of SECTION_IDS) {
      expect(container.querySelector(`section#${id}`)).not.toBeNull();
    }

    const page2Nav = screen.getByRole('navigation', { name: 'Page 2 navigation' });
    expect(
      within(page2Nav)
        .getByRole('link', { name: /previous: page 1/i })
        .getAttribute('href'),
    ).toBe('#page-1');
    expect(
      within(page2Nav)
        .getByRole('link', { name: /next: page 3/i })
        .getAttribute('href'),
    ).toBe('#page-3');
  });

  it('offers the bundled PDF, the creation flow and the way home', () => {
    render(<SampleBookPage />);
    const pdfLinks = screen.getAllByRole('link', { name: 'Download the sample PDF' });
    expect(pdfLinks.length).toBeGreaterThan(0);
    for (const link of pdfLinks) {
      expect(link.getAttribute('href')).toBe(SAMPLE_BOOK.pdf.href);
      expect(link.getAttribute('download')).toBe('juno-and-the-runaway-kite.pdf');
    }
    expect(existsSync(resolve(PUBLIC_DIR, `.${SAMPLE_BOOK.pdf.href}`))).toBe(true);

    for (const link of screen.getAllByRole('link', { name: 'Create your own book' })) {
      expect(link.getAttribute('href')).toBe('/register?next=%2Fdashboard%2Fbooks%2Fnew');
    }
    expect(screen.getByRole('link', { name: /← back to storyme home/i }).getAttribute('href')).toBe(
      '/',
    );
  });

  it('does not reach the API or any protected asset', () => {
    const fetchSpy = vi.spyOn(globalThis, 'fetch');
    const { container } = render(<SampleBookPage />);
    expect(fetchSpy).not.toHaveBeenCalled();
    const urls = [...container.querySelectorAll('[href], [src]')].map(
      (el) => el.getAttribute('href') ?? el.getAttribute('src') ?? '',
    );
    expect(urls.filter((url) => /\/api\/|^https?:/.test(url))).toEqual([]);
  });
});
